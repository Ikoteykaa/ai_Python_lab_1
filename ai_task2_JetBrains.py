"""ai_task2_JetBrains.py

Скрипт для перевірки можливості побудови трикутника за трьома сторонами.
"""


def is_valid_triangle(a: int, b: int, c: int) -> bool:
    """Перевіряє нерівність трикутника: кожна сторона повинна бути меншою за суму двох інших."""
    return (a < b + c) and (b < a + c) and (c < a + b)


def main() -> None:
    # Запит трьох цілочисельних значень сторін у користувача
    a = int(input("Введіть довжину сторони a: "))
    b = int(input("Введіть довжину сторони b: "))
    c = int(input("Введіть довжину сторони c: "))

    # Перевірка умови існування трикутника
    result = is_valid_triangle(a, b, c)

    # Виведення булевого результату на екран
    print(result)


if __name__ == "__main__":
    main()
